def norm(value):
    if value is None:
        return ""

    return (
        str(value)
        .strip()
        .replace("ي", "ی")
        .replace("ى", "ی")
        .replace("ك", "ک")
        .replace("\u200c", " ")
        .replace("\u00a0", " ")
    )


def main():

    db = SessionLocal()

    try:

        print("")
        print("=" * 150)
        print("PRE-VALIDATION")
        print("=" * 150)

        # ----------------------------------------------------
        # 1. بررسی رکوردهای DATA
        # ----------------------------------------------------

        if not DATA:
            raise RuntimeError("DATA is empty.")

        print("DATA ROWS:", len(DATA))

        # ----------------------------------------------------
        # 2. بررسی شهرستان‌ها
        # ----------------------------------------------------

        county_map = {}

        for county_name in COUNTY_NAMES:

            rows = db.execute(
                text("""
                    SELECT id, county_name
                    FROM gis_counties
                    WHERE TRIM(county_name) = TRIM(:name)
                """),
                {"name": county_name},
            ).fetchall()

            if len(rows) != 1:
                raise RuntimeError(
                    f"County mapping failed: {county_name} -> {rows}"
                )

            county_map[county_name] = rows[0][0]

        print("")
        print("COUNTY MAPPING")

        for name, county_id in county_map.items():
            print(f"{name} => {county_id}")

        # ----------------------------------------------------
        # 3. بررسی اینکه هیچ شهرستان ناشناخته‌ای در DATA نیست
        # ----------------------------------------------------

        data_counties = sorted({row[0] for row in DATA})

        missing_counties = [
            name for name in data_counties
            if name not in county_map
        ]

        if missing_counties:
            raise RuntimeError(
                f"DATA contains unknown counties: {missing_counties}"
            )

        # ----------------------------------------------------
        # 4. Disease IDs واقعی
        #
        # آبله intentionally NULL است چون در gis_diseases
        # رکورد آبله وجود ندارد.
        #
        # ما نباید بیماری دیگری را به جای آبله قرار دهیم.
        # ----------------------------------------------------

        disease_resolution = {

            "مراقبت سل (تست توبرکولین)": 76,

            "مراقبت بروسلوز (تست سرمی)": 81,

            "مراقبت سرمي مشمشه": 87,

            "تب برفکی": 82,

            "هاري": 83,

            "طاعون نشخوارکنندگان کوچک": 88,

            "مشمشه": 90,

            "شاربن": 98,

            "لامپی اسکین": 99,

            "بروسلوز": 85,

            # آبله فعلاً NULL
            # چون gis_diseases رکورد آن را ندارد.
            "آبله": None,
        }

        # ----------------------------------------------------
        # 5. Verify actual disease IDs
        # ----------------------------------------------------

        print("")
        print("DISEASE MAPPING")

        for disease_name, disease_id in disease_resolution.items():

            if disease_id is None:

                print(
                    f"{disease_name} => NULL "
                    "(not present in gis_diseases)"
                )

                continue

            row = db.execute(
                text("""
                    SELECT id, disease_name
                    FROM gis_diseases
                    WHERE id = :id
                """),
                {"id": disease_id},
            ).fetchone()

            if row is None:
                raise RuntimeError(
                    f"Disease ID {disease_id} does not exist."
                )

            print(
                f"{disease_name} => "
                f"{row[0]} / {row[1]}"
            )

        # ----------------------------------------------------
        # 6. ساخت رکوردهای آماده INSERT
        # ----------------------------------------------------

        prepared_rows = []

        for (
            county_name,
            disease_name,
            prediction_category,
            animal_type,
            value,
            source_sheet,
        ) in DATA:

            if county_name not in county_map:
                raise RuntimeError(
                    f"Unknown county in DATA: {county_name}"
                )

            if disease_name not in disease_resolution:
                raise RuntimeError(
                    f"Unknown disease mapping in DATA: {disease_name}"
                )

            if value is None:
                raise RuntimeError(
                    f"NULL prediction value: {county_name}, "
                    f"{disease_name}, {prediction_category}"
                )

            prepared_rows.append(
                {
                    "county_id": county_map[county_name],
                    "disease_id": disease_resolution[disease_name],
                    "county_name": county_name,
                    "disease_name": disease_name,
                    "prediction_category": prediction_category,
                    "animal_type": animal_type,
                    "prediction_value": Decimal(str(value)),
                    "source_sheet": source_sheet,
                }
            )

        # ----------------------------------------------------
        # 7. Duplicate validation
        # ----------------------------------------------------

        unique_keys = set()
        duplicates = []

        for row in prepared_rows:

            key = (
                row["county_id"],
                row["disease_name"],
                row["prediction_category"],
                row["animal_type"],
                PREDICTION_YEAR,
            )

            if key in unique_keys:
                duplicates.append(key)

            unique_keys.add(key)

        if duplicates:
            raise RuntimeError(
                f"Duplicate prediction rows detected: {duplicates[:20]}"
            )

        print("")
        print("PREPARED ROWS:", len(prepared_rows))
        print("UNIQUE ROWS:", len(unique_keys))

        # ----------------------------------------------------
        # 8. فقط بعد از تمام validationها DB تغییر می‌کند
        # ----------------------------------------------------

        print("")
        print("=" * 150)
        print("REBUILDING TABLE")
        print("=" * 150)

        db.execute(
            text("""
                DROP TABLE IF EXISTS gis_vaccination_predictions;
            """)
        )

        db.execute(
            text("""
                CREATE TABLE gis_vaccination_predictions (

                    id BIGSERIAL PRIMARY KEY,

                    county_id INTEGER NOT NULL,

                    disease_id INTEGER NULL,

                    prediction_year INTEGER NOT NULL,

                    prediction_category VARCHAR(200) NOT NULL,

                    animal_type VARCHAR(150),

                    prediction_value NUMERIC(14,2) NOT NULL,

                    source VARCHAR(20) NOT NULL DEFAULT 'EXCEL',

                    source_file VARCHAR(255) NOT NULL,

                    source_sheet VARCHAR(200),

                    created_at TIMESTAMP NOT NULL
                        DEFAULT CURRENT_TIMESTAMP,

                    updated_at TIMESTAMP NOT NULL
                        DEFAULT CURRENT_TIMESTAMP,

                    CONSTRAINT fk_gis_vacc_prediction_county
                        FOREIGN KEY (county_id)
                        REFERENCES gis_counties(id),

                    CONSTRAINT fk_gis_vacc_prediction_disease
                        FOREIGN KEY (disease_id)
                        REFERENCES gis_diseases(id),

                    CONSTRAINT uq_gis_vacc_prediction
                        UNIQUE (
                            county_id,
                            disease_id,
                            prediction_year,
                            prediction_category,
                            animal_type
                        )
                );
            """)
        )

        # ----------------------------------------------------
        # 9. INSERT
        # ----------------------------------------------------

        insert_sql = text("""
            INSERT INTO gis_vaccination_predictions (
                county_id,
                disease_id,
                prediction_year,
                prediction_category,
                animal_type,
                prediction_value,
                source,
                source_file,
                source_sheet
            )
            VALUES (
                :county_id,
                :disease_id,
                :prediction_year,
                :prediction_category,
                :animal_type,
                :prediction_value,
                'EXCEL',
                :source_file,
                :source_sheet
            )
        """)

        for row in prepared_rows:

            db.execute(
                insert_sql,
                {
                    "county_id": row["county_id"],
                    "disease_id": row["disease_id"],
                    "prediction_year": PREDICTION_YEAR,
                    "prediction_category": row["prediction_category"],
                    "animal_type": row["animal_type"],
                    "prediction_value": row["prediction_value"],
                    "source_file": SOURCE_FILE,
                    "source_sheet": row["source_sheet"],
                },
            )

        db.commit()

        # ----------------------------------------------------
        # 10. Verification
        # ----------------------------------------------------

        total = db.execute(
            text("""
                SELECT COUNT(*)
                FROM gis_vaccination_predictions
            """)
        ).scalar()

        print("")
        print("=" * 150)
        print("FINAL VERIFICATION")
        print("=" * 150)

        print("TOTAL ROWS:", total)

        if total != len(prepared_rows):
            raise RuntimeError(
                f"Row count mismatch: expected {len(prepared_rows)}, "
                f"got {total}"
            )

        # شهرستان‌های دارای رکورد
        county_count = db.execute(
            text("""
                SELECT COUNT(DISTINCT county_id)
                FROM gis_vaccination_predictions
            """)
        ).scalar()

        print("COUNTIES:", county_count)

        if county_count != 8:
            raise RuntimeError(
                f"Expected 8 counties, got {county_count}"
            )

        # بررسی FK شهرستان
        invalid_counties = db.execute(
            text("""
                SELECT COUNT(*)
                FROM gis_vaccination_predictions p
                LEFT JOIN gis_counties c
                    ON c.id = p.county_id
                WHERE c.id IS NULL
            """)
        ).scalar()

        print("INVALID COUNTY FK:", invalid_counties)

        if invalid_counties != 0:
            raise RuntimeError("Invalid county foreign keys.")

        # بررسی FK بیماری
        invalid_diseases = db.execute(
            text("""
                SELECT COUNT(*)
                FROM gis_vaccination_predictions p
                LEFT JOIN gis_diseases d
                    ON d.id = p.disease_id
                WHERE p.disease_id IS NOT NULL
                  AND d.id IS NULL
            """)
        ).scalar()

        print("INVALID DISEASE FK:", invalid_diseases)

        if invalid_diseases != 0:
            raise RuntimeError("Invalid disease foreign keys.")

        # ----------------------------------------------------
        # 11. نمایش نهایی
        # ----------------------------------------------------

        rows = db.execute(
            text("""
                SELECT
                    p.id,
                    c.county_name,
                    d.disease_name,
                    p.prediction_category,
                    p.animal_type,
                    p.prediction_value,
                    p.prediction_year,
                    p.source
                FROM gis_vaccination_predictions p
                JOIN gis_counties c
                    ON c.id = p.county_id
                LEFT JOIN gis_diseases d
                    ON d.id = p.disease_id
                ORDER BY
                    c.id,
                    p.id
            """)
        ).fetchall()

        print("")
        print("=" * 180)
        print("GIS VACCINATION PREDICTIONS")
        print("=" * 180)

        for row in rows:
            print(row)

        print("")
        print("=" * 180)
        print("RESULT")
        print("=" * 180)

        print("TABLE:", "gis_vaccination_predictions")
        print("ROWS:", total)
        print("COUNTIES:", county_count)
        print("INVALID COUNTY FK:", invalid_counties)
        print("INVALID DISEASE FK:", invalid_diseases)
        print("SOURCE:", SOURCE_FILE)
        print("YEAR:", PREDICTION_YEAR)
        print("STATUS:", "PASS")

    except Exception:
        db.rollback()
        raise

    finally:
        db.close()


if __name__ == "__main__":
    main()